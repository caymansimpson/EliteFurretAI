# Model Double Battle Order
class MDBO(BattleOrder):
    """
    Encodes and decodes double battle orders for use in ML models.
    Supports teampreview, force switch, turn, and default orders.
    """

    # Order types
    FORCE_SWITCH = "force_switch"
    TEAMPREVIEW = "teampreview"
    TURN = "turn"
    DEFAULT = "default"

    def __init__(self, type: str, msg: str = ""):
        """
        Initialize an MDBO object.
        type: one of FORCE_SWITCH, TEAMPREVIEW, TURN, DEFAULT
        msg: showdown protocol string (e.g., "/choose move 1, move 2")
        """
        assert type in [
            self.FORCE_SWITCH,
            self.TEAMPREVIEW,
            self.TURN,
            self.DEFAULT,
        ], "mdbo type not recognized"
        self._type = type
        self._msg = msg

        # For teampreview, standardize the order so that pairs are treated the same
        if self._type == MDBO.TEAMPREVIEW:
            msg = "".join(char for char in msg.replace("/team ", "") if char.isdigit())
            first_less = msg[0] if msg[0] < msg[1] else msg[1]
            first_most = msg[0] if msg[0] > msg[1] else msg[1]
            second_less = msg[2] if msg[2] < msg[3] else msg[3]
            second_most = msg[2] if msg[2] > msg[3] else msg[3]
            self._msg = f"/team {first_less}{first_most}{second_less}{second_most}"

    @property
    def message(self) -> str:
        """
        Returns the showdown protocol string for this order.
        """
        if self._type == self.DEFAULT:
            return "/choose default"
        else:
            assert self._msg is not None
            return self._msg

    def to_int(self) -> int:
        """
        Converts this MDBO to an integer for model use.
        """
        if self._type == self.DEFAULT:
            return -1

        assert self._msg is not None, (
            "msg is None and not default; cant turn it into an int"
        )
        if self._type == self.TEAMPREVIEW:
            # Remove spaces/commas and look up in teampreview mapping
            key = re.sub(r"[\s,]", "", self._msg[5:])
            assert key in _TEAMPREVIEW_ORDER_TO_INT, (
                f"{key} not in TEAMPREVIEW_ORDER_TO_INT. Message: {self._msg}"
            )
            return _TEAMPREVIEW_ORDER_TO_INT[key]
        else:
            # For turn/force_switch: parse both orders and encode as a single int
            orders = self._msg[8:].split(", ")
            assert len(orders) == 2, (
                f"Only got one order for a double battle order: {self._msg}"
            )
            assert orders[0] in _ORDER_MAPPINGS_TO_INT, (
                f"{orders[0]} not in ORDER_MAPPINGS_TO_INT. Label: {self._msg}"
            )
            assert orders[1] in _ORDER_MAPPINGS_TO_INT, (
                f"{orders[1]} not in ORDER_MAPPINGS_TO_INT. Label: {self._msg}"
            )
            return (
                _ORDER_MAPPINGS_TO_INT[orders[0]] * len(_ORDER_MAPPINGS_TO_INT)
                + _ORDER_MAPPINGS_TO_INT[orders[1]]
            )

    def to_double_battle_order(
        self,
        battle: DoubleBattle,
        request: Optional[dict] = None,
    ) -> Union[DoubleBattleOrder, DefaultBattleOrder]:
        """
        Converts this MDBO to a PyPokéEnv DoubleBattleOrder or DefaultBattleOrder.
        """
        assert not self.message.startswith("/team"), (
            "MDBO cannot be converted into DBO when it is a teampreview"
        )
        assert battle.player_role is not None, (
            "Cannot convert MDBO to DBO when player_role is None because we assume we have the right perspective"
        )
        request_data = request if request is not None else battle.last_request
        orders: List[SingleBattleOrder] = []
        for i, order in enumerate(self.message.replace("/choose ", "").split(", ")):
            if order == "pass":
                orders.append(PassBattleOrder())
            elif order == "default":
                return DefaultBattleOrder()
            elif order.startswith("switch "):
                # Switch to a specific Pokémon from the team
                # In Showdown protocol, "switch N" refers to the N-th Pokemon in the
                # request's side.pokemon list (1-indexed). After teampreview, this list
                # is reordered so positions 1-4 are the Pokemon brought to battle.
                #
                # IMPORTANT: We MUST use battle.last_request to get the correct order,
                # because battle.team is a dict populated during teampreview and its
                # iteration order may not match the request's Pokemon order.
                switch_idx = int(order[7]) - 1  # Convert 1-indexed to 0-indexed

                # Get Pokemon order from the last request's side.pokemon list
                if request_data and "side" in request_data:
                    request_pokemon = request_data["side"]["pokemon"]
                    if switch_idx < len(request_pokemon):
                        # Get the identifier (e.g., "p1: Iron Hands") from request
                        ident = request_pokemon[switch_idx]["ident"]
                        # Look up the Pokemon object from battle.team using identifier
                        if ident in battle.team:
                            mon = battle.team[ident]
                            orders.append(SingleBattleOrder(order=mon))
                        else:
                            raise ValueError(
                                f"Pokemon {ident} from request not found in battle.team. "
                                f"Team keys: {list(battle.team.keys())}"
                            )
                    else:
                        raise ValueError(
                            f"Switch index {switch_idx + 1} out of bounds for request "
                            f"pokemon list of size {len(request_pokemon)}"
                        )
                else:
                    # Fallback to old behavior if no request available (eg supervised learning)
                    team_list = list(battle.team.values())
                    if switch_idx < len(team_list):
                        mon = team_list[switch_idx]
                        orders.append(SingleBattleOrder(order=mon))
                    else:
                        raise ValueError(
                            f"Switch index {switch_idx + 1} out of bounds for team of size {len(team_list)}"
                        )

            # move
            else:
                moving_mon = battle.active_pokemon[i]
                assert moving_mon is not None, (
                    "Cannot convert an order for a pokemon when it is not active"
                )

                move_idx = int(order[5]) - 1  # Convert 1-indexed to 0-indexed

                # Special case: struggle/recharge are not in the Pokemon's move list
                # but can appear in available_moves when all PP is depleted.
                # In this case, use available_moves instead of the Pokemon's moveset.
                if len(battle.available_moves[i]) == 1 and battle.available_moves[i][
                    0
                ].id in ["struggle", "recharge"]:
                    # For struggle/recharge, any "move X" should use this move
                    move = battle.available_moves[i][0]
                elif request_data:
                    move = _get_request_move_by_slot_from_request(
                        battle,
                        request_data,
                        i,
                        move_idx,
                        moving_mon,
                    )
                else:
                    # Normal case: look up move from Pokemon's moveset
                    move_keys = list(moving_mon.moves.keys())
                    if move_idx >= len(move_keys):
                        raise ValueError(
                            f"Move index {move_idx + 1} out of bounds for {moving_mon.species} "
                            f"with {len(move_keys)} moves"
                        )
                    move_key = move_keys[move_idx]
                    move = moving_mon.moves[move_key]

                target = DoubleBattle.EMPTY_TARGET_POSITION
                # Extract target from order string (e.g., "move 1 -2" or "move 1 2 terastallize")
                # Remove terastallize suffix first, then parse target after move number
                order_without_tera = order.replace(" terastallize", "")
                # Target starts after "move X " (7 chars), strip whitespace for ally targets
                if len(order_without_tera) > 7:
                    target_str = order_without_tera[7:].strip()
                    if target_str in ["-1", "-2", "1", "2"]:
                        target = int(target_str)

                orders.append(
                    SingleBattleOrder(
                        order=move,
                        terastallize="terastallize" in order,
                        move_target=target,
                    )
                )

        return DoubleBattleOrder(first_order=orders[0], second_order=orders[1])

    @staticmethod
    def action_space() -> int:
        """
        Returns the total number of possible double battle orders (for model output size).
        """
        return len(_INT_TO_ORDER_MAPPINGS) * len(_INT_TO_ORDER_MAPPINGS)

    @staticmethod
    def teampreview_space() -> int:
        """
        Returns the total number of possible teampreview orders (for model output size).
        """
        return len(_INT_TO_TEAMPREVIEW_ORDER)

    @staticmethod
    def from_int(i: int, type: str):
        """
        Converts an integer and type back to an MDBO object.
        """
        assert type in [MDBO.FORCE_SWITCH, MDBO.TEAMPREVIEW, MDBO.TURN, MDBO.DEFAULT]
        if i == -1:
            return MDBO(MDBO.DEFAULT)
        elif type == MDBO.TEAMPREVIEW:
            assert i < len(_INT_TO_TEAMPREVIEW_ORDER)
            return MDBO(type, "/team " + _INT_TO_TEAMPREVIEW_ORDER[i])
        else:
            assert i < len(_INT_TO_ORDER_MAPPINGS) * len(_INT_TO_ORDER_MAPPINGS)
            order_1 = _INT_TO_ORDER_MAPPINGS[i // len(_INT_TO_ORDER_MAPPINGS)]
            order_2 = _INT_TO_ORDER_MAPPINGS[i % len(_INT_TO_ORDER_MAPPINGS)]
            return MDBO(type, "/choose " + order_1 + ", " + order_2)


_MOVE_ORDERS = (
    list(itertools.permutations(["p1a", "p1b", "p2a", "p2b"], 4))
    + [x + ("",) for x in itertools.permutations(["p1a", "p1b", "p2a", "p2b"], 3)]
    + [x + ("", "") for x in itertools.permutations(["p1a", "p1b", "p2a", "p2b"], 2)]
    + [x + ("", "", "") for x in itertools.permutations(["p1a", "p1b", "p2a", "p2b"], 1)]
    + [("", "", "", "")]
)
_MOVE_ORDER_MAPPINGS = {order: i for i, order in enumerate(_MOVE_ORDERS)}


def _get_request_move_by_slot_from_request(
    battle: DoubleBattle,
    request,
    slot: int,
    move_idx: int,
    moving_mon,
):
    if not request:
        raise ValueError(f"Missing request data for slot {slot} on {moving_mon.species}")

    active_requests = request.get("active", [])
    if slot >= len(active_requests):
        raise ValueError(f"Missing active request for slot {slot} on {moving_mon.species}")

    slot_request = active_requests[slot]
    if not isinstance(slot_request, dict) or "moves" not in slot_request:
        raise ValueError(
            f"Missing move request data for slot {slot} on {moving_mon.species}"
        )

    request_moves = slot_request["moves"]
    if move_idx >= len(request_moves):
        raise ValueError(
            f"Move index {move_idx + 1} out of bounds for request on {moving_mon.species} "
            f"with {len(request_moves)} raw move slots"
        )

    move_request = dict(request_moves[move_idx])
    move_request["disabled"] = False
    decoded_moves = moving_mon.available_moves_from_request({"moves": [move_request]})
    if not decoded_moves:
        raise ValueError(
            f"Could not decode request move slot {move_idx + 1} for {moving_mon.species}"
        )
    return decoded_moves[0]


# The idea of this class is that it can convert teampreview orders into a single int
# to help with RL tasks where we want a single action representing the entire teampreview order
class MoveOrderEncoder:
    @staticmethod
    def action_space() -> int:
        """
        Returns the total number of possible move orders (for model output size).
        """
        return len(_MOVE_ORDER_MAPPINGS)

    @staticmethod
    def encode(move_order: List[str]) -> int:
        """
        Encodes a list of up to 4 Pokémon IDs into an integer representing the move order.

        move_order: List of Pokémon IDs (up to 4; eg [p1a, p2b, p3a])
        """
        assert len(move_order) <= 4, "move_order can have at most 4 Pokémon"
        if len(move_order) < 4:
            move_order = move_order + [""] * (
                4 - len(move_order)
            )  # Pad with empty strings
        order: tuple[str, str, str, str] = (
            move_order[0],
            move_order[1],
            move_order[2],
            move_order[3],
        )
        return _MOVE_ORDER_MAPPINGS.get(order, -1)


